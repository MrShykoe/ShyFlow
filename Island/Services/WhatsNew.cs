    // всё, что вышло после from и не новее текущей версии, по порядку
    public static List<(Version ver, Feature f)> Since(Version from)
    {
        var cur = Updater.Current;
        return All.Where(r => r.Ver > from && r.Ver <= cur).OrderBy(r => r.Ver)
                  .SelectMany(r => r.Items.Select(f => (r.Ver, f))).ToList();
    }
